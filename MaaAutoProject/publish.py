"""MaaAuto publishing script: produces the source package a GitHub Release needs.

Output:
    release/MaaAuto_Source.zip    source package (the source root sits at the top)

Usage:
    python publish.py                 # full: build.py + Source.zip
    python publish.py --skip-build    # skip build.py
    python publish.py --keep          # do not clean old files in release/
    python publish.py --debug         # build.py keeps the console window

Requires:
    pip install pyinstaller
    APP_VERSION already bumped in app_info.py

Agreement with the installer side (frozen 2026-09):
  - MaaAuto_Source.zip holds the source root directly (main.py / app_info.py /
    requirements.txt / ui/ / ...), with no MaaAutoProject/ level
  - this script only produces Source.zip
  - the online package (MaaAuto_Online_vX.X.X-Windows-x64.exe) comes from the installer
    side, MaaAutoInstaller/build_installer.py
  - the user uploads both assets to the same GitHub Release by hand
  - the Release tag must be PEP 440 (v2.1.0 / v2.1.0b1), never v2.1.0-beta
"""

import os
import re
import sys
import hashlib
import zipfile
import argparse
import subprocess
from pathlib import Path

# Same as build.py: on an English system / CI stdout is cp1252 and Chinese output crashes.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


ROOT = Path(__file__).resolve().parent
DIST_DIR = ROOT / "dist"
RELEASE_DIR = ROOT / "release"
APP_NAME = "MaaAuto"

# Top-level dirs excluded from Source.zip (not recursive; dirs[:] filtering handles subdirs)
EXCLUDE_TOP = {
    ".git", ".hg", ".svn",
    ".idea", ".vscode",
    "venv", ".venv", "env", ".env",
    "node_modules",
    "__pycache__",
    "dist", "build", "release",
    "config", "logs",          # created at runtime, not source
}

# Top-level files excluded from Source.zip
EXCLUDE_FILES = {
    "MaaAuto.spec",
    "_version_info.txt",       # generated by build.py, regenerated anyway
    ".DS_Store",
    "Thumbs.db",
    # ---- dev / release scripts (users do not need them) ----
    "publish.py",              # release script
    "deploy_dev.py",           # helper that deploys locally to D:\MaaAuto
    "diagnose.py",             # environment diagnostics script
    "selftest.py",             # self-test script (if present)
}

# Suffixes excluded at any depth
EXCLUDE_SUFFIXES = (".pyc", ".pyo", ".log")

# Release rule: stay inside the PEP 440 subset that both the app's packaging and the
# upgrader's hand-written parser accept; the installer build checks the same thing.
# Allowed: 2.1.0 / v2.1.0 (the tag prefix v is the publisher's call; APP_VERSION has none)
#       2.1.0b1 / 2.1.0rc2 / 2.1.0.post1
# Rejected: 2.1.0-beta / 2.1.0.dev1 / 2.1.0+local
VERSION_RE = re.compile(r"^\d+\.\d+\.\d+(?:(?:a|b|rc)\d+)?(?:\.post\d+)?$")


# --------------------------------------------------------------------------- #
# Helpers
# --------------------------------------------------------------------------- #
def read_app_info():
    info = {"APP_NAME": APP_NAME, "APP_VERSION": "0.0.0"}
    path = ROOT / "app_info.py"
    if path.exists():
        text = path.read_text(encoding="utf-8")
        for key in ("APP_NAME", "APP_VERSION"):
            m = re.search(rf'^{key}\s*=\s*["\']([^"\']*)["\']', text, re.M)
            if m:
                info[key] = m.group(1)
    return info


def check_version_format(version: str) -> bool:
    """Check that APP_VERSION falls inside the version-syntax subset both sides agreed on.

    The upgrader uses its own parser and rejects .devN / +local / -beta; the app uses
    packaging, which is looser. Only versions inside the subset behave the same both ways.
    """
    if VERSION_RE.match(version or ""):
        print(f"[publish] 版本语法检查通过: {version}")
        return True

    print()
    print("=" * 60)
    print(f"[warn] APP_VERSION = {version!r} 不符合发布约定")
    print("       允许: X.Y.Z / X.Y.ZaN / X.Y.ZbN / X.Y.ZrcN / X.Y.Z.postN")
    print("       不允许: -beta / .devN / +local / 其他非 PEP 440 写法")
    print("       版本规范见 README「升级与版本」一节")
    print("=" * 60)
    print()
    return False


def sha256_of_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def human_size(n: int) -> str:
    if n >= 1024 * 1024:
        return f"{n / (1024 * 1024):.2f} MB"
    if n >= 1024:
        return f"{n / 1024:.1f} KB"
    return f"{n} B"


# --------------------------------------------------------------------------- #
# build.py
# --------------------------------------------------------------------------- #
def run_build(debug=False):
    build_script = ROOT / "build.py"
    if not build_script.exists():
        print(f"[error] 找不到 build.py: {build_script}")
        sys.exit(1)

    cmd = [sys.executable, str(build_script)]
    if debug:
        cmd.append("--debug")

    print(f"[publish] 调用 build.py：{' '.join(cmd)}")
    ret = subprocess.call(cmd, cwd=str(ROOT))
    if ret != 0:
        print(f"[error] build.py 失败，退出码 {ret}")
        sys.exit(ret)


# --------------------------------------------------------------------------- #
# Source.zip
# --------------------------------------------------------------------------- #
def make_source_zip(version: str) -> Path:
    """Package the source into release/MaaAuto_Source.zip.
    The source root sits at the top level.
    """
    out = RELEASE_DIR / "MaaAuto_Source.zip"
    if out.exists():
        out.unlink()

    print(f"[publish] 生成 Source.zip: {out.name}")

    count = 0
    skipped = []
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED, compresslevel=9) as zf:
        for root, dirs, files in os.walk(ROOT):
            root_path = Path(root)

            dirs[:] = [
                d for d in dirs
                if d not in EXCLUDE_TOP and not d.startswith(".")
            ]

            rel_root = root_path.relative_to(ROOT)

            for fname in files:
                if not rel_root.parts and fname in EXCLUDE_FILES:
                    skipped.append(fname)
                    continue
                if fname.endswith(EXCLUDE_SUFFIXES):
                    continue
                if fname.startswith(".") and fname != ".gitignore":
                    continue

                fpath = root_path / fname
                arcname = fpath.relative_to(ROOT).as_posix()
                try:
                    zf.write(fpath, arcname)
                    count += 1
                except Exception as e:
                    print(f"[warn] 跳过 {arcname}: {e}")

    size = out.stat().st_size
    print(f"[publish] Source.zip 完成：{count} 个文件，{human_size(size)}")
    if skipped:
        print(f"[publish] 已排除开发脚本: {', '.join(sorted(set(skipped)))}")
    return out


# --------------------------------------------------------------------------- #
# Dependency checks
# --------------------------------------------------------------------------- #
def check_dependencies():
    """Check three kinds of dependency:
      1. pip packages (must be declared in requirements.txt)
      2. local modules (the project root must hold the matching .py file)
      3. key resource files (the dirs build.py passes to add-data)
    """
    problems = []

    # ---- 1) pip packages ----
    req = ROOT / "requirements.txt"
    if not req.exists():
        problems.append("requirements.txt 不存在")
        req_text = ""
    else:
        try:
            req_text = req.read_text(encoding="utf-8").lower()
        except Exception:
            req_text = ""

    required_pip = {
        "pyside6": "PySide6",
        "pyinstaller": "pyinstaller",
        "psutil": "psutil",
        "pillow": "Pillow",
        "opencv": "opencv-python-headless",   # <- what vision.py multi-scale matching needs
        "packaging": "packaging",
        "pywin32": "pywin32",
    }
    for key, pkg in required_pip.items():
        if key not in req_text:
            problems.append(f"requirements.txt 缺少 pip 包: {pkg}")

    # ---- 2) local modules ----
    local_modules = [
        "serverchan_sdk.py",
    ]
    for name in local_modules:
        if not (ROOT / name).exists():
            problems.append(
                f"缺少本地模块: {name}\n"
                f"          （notifier.py / settings_page.py 依赖它）\n"
                f"          （从 git 或备份恢复，或改用 PyPI 的 serverchan-sdk）"
            )

    # ---- 3) resource dirs ----
    resource_dirs = ["resources", "themes", "i18n"]
    for name in resource_dirs:
        if not (ROOT / name).is_dir():
            problems.append(f"缺少资源目录: {name}/")

    # ---- report ----
    if problems:
        print()
        print("=" * 60)
        print("[warn] 发布前检查发现问题：")
        print("=" * 60)
        for p in problems:
            print(f"  - {p}")
        print("=" * 60)
        print()
    else:
        print("[publish] 依赖检查通过")


# --------------------------------------------------------------------------- #
# Main flow
# --------------------------------------------------------------------------- #
def main():
    parser = argparse.ArgumentParser(
        description="MaaAuto 发布脚本",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--skip-build", action="store_true",
                        help="跳过 build.py（复用现有 dist/）")
    parser.add_argument("--keep", action="store_true",
                        help="不清理 release/ 旧 zip")
    parser.add_argument("--debug", action="store_true",
                        help="build.py 保留控制台窗口")
    args = parser.parse_args()

    info = read_app_info()
    version = info["APP_VERSION"]
    # The version syntax is a cross-repo protocol: the upgrader's own parser only knows
    # the agreed subset, so block here or the zip says "new version" and the upgrader balks.
    if not check_version_format(version):
        print("[publish] 已中止：请先把 app_info.py 的 APP_VERSION 改成允许的格式。")
        sys.exit(2)

    print("=" * 60)
    print(f"MaaAuto 发布脚本 —— v{version}")
    print("=" * 60)
    print(f"项目根目录：{ROOT}")
    print(f"Python：{sys.version.split()[0]}")
    print("=" * 60)

    # 0. Dependency checks (first, to surface problems early)
    check_dependencies()

    # 1. release/ directory
    RELEASE_DIR.mkdir(exist_ok=True)
    if not args.keep:
        old_zips = list(RELEASE_DIR.glob("*.zip"))
        for old in old_zips:
            print(f"[clean] 删除旧文件: {old.name}")
            old.unlink()

    # 2. Build the app
    if not args.skip_build:
        run_build(debug=args.debug)
    else:
        print("[publish] 跳过 build.py（--skip-build）")

    # 3. Source.zip
    source_zip = make_source_zip(version)

    # 4. sha256
    src_sha = sha256_of_file(source_zip)

    # 5. Report
    print()
    print("=" * 60)
    print(f"[OK] 发布包已生成：{RELEASE_DIR}")
    print("=" * 60)
    print()
    print(f"  {source_zip.name}")
    print(f"    用途：升级器（upgrade.exe）源码包")
    print(f"    大小：{human_size(source_zip.stat().st_size)}")
    print(f"    sha256：{src_sha}")
    print()
    print("=" * 60)
    print("【下一步：手动上传两个 asset】")
    print("=" * 60)
    print()
    print(f"  - MaaAuto_Source.zip")
    print(f"      ← 本脚本刚生成，位于 release/ 目录")
    print()
    print(f"  - MaaAuto_Online_v{version}-Windows-x64.exe")
    print(f"      ← 由安装器侧 MaaAutoInstaller/build_installer.py 生成")
    print(f"         路径：MaaAutoInstaller/dist/")
    print()
    print("  两个 asset 一起上传到同一个 GitHub Release。")
    print()
    print("=" * 60)
    print("  注意：")
    print(f"    * tag（必须 PEP 440）：v{version}")
    print("    * tag 不能是 v2.1.0-beta，只能是 v2.1.0 / v2.1.0b1 / v2.1.0rc1")
    print("    * Source.zip 是升级器必需的，别忘了传")
    print()


if __name__ == "__main__":
    main()