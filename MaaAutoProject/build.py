"""MaaAuto one-shot packaging script (PyInstaller).

Usage:
    python build.py                 # default: onedir, no console
    python build.py --debug         # keep the console window
    python build.py --onefile       # single-file mode (slow start, not recommended)
    python build.py --keep-build    # do not clean build/ and dist/
    python build.py --no-clean      # skip pyinstaller --clean

Output:
    dist/MaaAuto/MaaAuto.exe
    dist/MaaAuto/_internal/...
    dist/MaaAuto/requirements.txt   (extra file)
    dist/MaaAuto/README.md
    dist/MaaAuto/LICENSE
    dist/MaaAuto/CHANGELOG.md
    dist/MaaAuto/_version_info.txt

Requires:
    pip install pyinstaller
"""

import os
import re
import sys
import shutil
import argparse
import subprocess
from pathlib import Path

# On CI / an English system stdout is cp1252 and printing Chinese raises UnicodeEncodeError, so force UTF-8.
for _stream in (sys.stdout, sys.stderr):
    try:
        _stream.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# --------------------------------------------------------------------------- #
# Paths
# --------------------------------------------------------------------------- #
ROOT = Path(__file__).resolve().parent
DIST_DIR = ROOT / "dist"
BUILD_DIR = ROOT / "build"
SPEC_FILE = ROOT / "MaaAuto.spec"
VERSION_FILE = ROOT / "_version_info.txt"

# Resource dirs bundled into the package (source path -> path inside the bundle)
DATA_DIRS = [
    ("resources", "resources"),
    ("themes",    "themes"),
    ("i18n",      "i18n"),
]

# * Extra files copied to the top level of dist/MaaAuto/ (not via PyInstaller add-data)
EXTRA_DIST_FILES = [
    "requirements.txt",
    "README.md",
    "LICENSE",
    "CHANGELOG.md",
    "_version_info.txt",   # generated by this script
]

# Implicit imports PyInstaller often misses (Pillow / psutil / cv2 ...)
HIDDEN_IMPORTS = [
    "PIL",
    "PIL.Image",
    "PIL.ImageGrab",    # <- what vision.grab() needs to capture the screen
    "psutil",
    "win32gui",
    "win32process",
    "win32con",
    "winreg",
    "serverchan_sdk",   # <- local file serverchan_sdk.py; make sure it lands in the exe
    "cv2",              # <- what vision.py multi-scale matching needs (opencv-python-headless)
]

# Size optimisation: exclude these packages explicitly
#
# * Never exclude numpy: opencv-python-headless (cv2) from requirements.txt needs it.
#   Excluding numpy here once broke `import cv2` in the packed build; matching then
#   degraded to exact pixels, installed build only - blamed on bad captures.
EXCLUDES = [
    "matplotlib",
    "scipy",
    "pandas",
    "IPython",
    "jupyter",
    "notebook",
    "PyQt5",
    "PyQt6",
    "PySide2",
    "wx",
    # Since 1.0.2 pyautogui is no longer used, so these companion packages can go (saves a few MB)
    "pyscreeze",
    "pygetwindow",
    "pymsgbox",
    "mouseinfo",
    "tkinter",
]

PYCACHE_SKIP_DIRS = {
    ".git", ".hg", ".svn",
    ".idea", ".vscode",
    "venv", ".venv", "env", ".env",
    "node_modules",
    "__pycache__",
    "dist", "build",
}


# --------------------------------------------------------------------------- #
# Metadata
# --------------------------------------------------------------------------- #
def read_app_info():
    info = {
        "APP_NAME": "MaaAuto",
        "APP_DISPLAY_NAME": "MaaAuto",
        "APP_VERSION": "0.0.0",
        "APP_ORG": "MaaAuto",
        "APP_GITHUB": "",
        "APP_EMAIL": "",
        "APP_LICENSE": "MIT",
    }
    path = ROOT / "app_info.py"
    if not path.exists():
        return info
    text = path.read_text(encoding="utf-8")
    for key in list(info.keys()):
        m = re.search(rf'^{key}\s*=\s*["\']([^"\']*)["\']', text, re.M)
        if m:
            info[key] = m.group(1)
    return info


def version_tuple(ver_str):
    m = re.match(r"(\d+)\.(\d+)\.(\d+)", ver_str or "")
    if not m:
        return (0, 0, 0, 0)
    return tuple(int(x) for x in m.groups()) + (0,)


# --------------------------------------------------------------------------- #
# version_info.txt generation
# --------------------------------------------------------------------------- #
def write_version_file(info):
    ver = version_tuple(info["APP_VERSION"])
    vt = ", ".join(str(x) for x in ver)
    name = info.get("APP_DISPLAY_NAME") or info.get("APP_NAME", "MaaAuto")
    company = info.get("APP_ORG", name)
    copyright_text = f"Copyright (C) 2024-2026 {company}. All rights reserved."
    license_text = info.get("APP_LICENSE", "")
    github = info.get("APP_GITHUB", "")
    email = info.get("APP_EMAIL", "")

    content = f"""# UTF-8
#
# PyInstaller 生成的 Windows 版本资源文件
# 由 build.py 自动生成，请勿手动修改。
#
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({vt}),
    prodvers=({vt}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        u'080404B0',
        [StringStruct(u'CompanyName',      u'{company}'),
         StringStruct(u'FileDescription',  u'{name}'),
         StringStruct(u'FileVersion',      u'{info["APP_VERSION"]}'),
         StringStruct(u'InternalName',     u'{info["APP_NAME"]}'),
         StringStruct(u'LegalCopyright',   u'{copyright_text}'),
         StringStruct(u'LegalTrademarks',  u''),
         StringStruct(u'OriginalFilename', u'{info["APP_NAME"]}.exe'),
         StringStruct(u'ProductName',      u'{name}'),
         StringStruct(u'ProductVersion',   u'{info["APP_VERSION"]}'),
         StringStruct(u'Comments',         u'{github} {email}'.strip()),
         StringStruct(u'License',          u'{license_text}')])
    ]),
    VarFileInfo([VarStruct(u'Translation', [2052, 1200])])
  ]
)
"""
    VERSION_FILE.write_text(content, encoding="utf-8")
    return VERSION_FILE


# --------------------------------------------------------------------------- #
# Cleanup
# --------------------------------------------------------------------------- #
def clean_artifacts():
    for p in (DIST_DIR, BUILD_DIR):
        if p.exists():
            print(f"[clean] 删除 {p}")
            shutil.rmtree(p, ignore_errors=True)
    if SPEC_FILE.exists():
        print(f"[clean] 删除 {SPEC_FILE.name}")
        try:
            SPEC_FILE.unlink()
        except Exception:
            pass


def clean_pycache(root: Path = ROOT):
    removed = 0
    for dirpath, dirnames, _files in os.walk(root, topdown=True):
        dirnames[:] = [d for d in dirnames if d.lower() not in PYCACHE_SKIP_DIRS]
        if "__pycache__" in dirnames:
            p = Path(dirpath) / "__pycache__"
            shutil.rmtree(p, ignore_errors=True)
            removed += 1
            dirnames.remove("__pycache__")
    if removed:
        print(f"[pycache] 清理 {removed} 个 __pycache__")


# --------------------------------------------------------------------------- #
# Environment checks
# --------------------------------------------------------------------------- #
def ensure_pyinstaller():
    try:
        import PyInstaller  # noqa: F401
        return True
    except ImportError:
        pass
    print("=" * 60)
    print("未检测到 PyInstaller。")
    print("请先安装：pip install pyinstaller")
    print("=" * 60)
    return False


# --------------------------------------------------------------------------- #
# Command assembly
# --------------------------------------------------------------------------- #
def build_command(args, info, version_file):
    cmd = [sys.executable, "-m", "PyInstaller"]
    cmd.append("--noconfirm")
    if not args.no_clean:
        cmd.append("--clean")

    cmd += ["--name", info["APP_NAME"]]

    icon = ROOT / "resources" / "icon.ico"
    if icon.exists():
        cmd += ["--icon", str(icon)]
    else:
        print(f"[warn] 找不到图标 {icon}，将使用默认图标。")

    cmd.append(str(ROOT / "main.py"))
    cmd.append("--onefile" if args.onefile else "--onedir")
    cmd.append("--console" if args.debug else "--windowed")

    # Since 3.0.0 admin rights come from the manifest embedded in the exe (the Inno
    # installer no longer writes RUNASADMIN), i.e. one UAC prompt per start, no HKCU flag.
    cmd.append("--uac-admin")

    # UPX off: antivirus false-positives on UPX-packed binaries are common, and UPX
    # often corrupts Qt DLLs. (The installer only set a PYI_DISABLE_UPX environment
    # variable, which PyInstaller ignores; this passes --noupx explicitly to match.)
    cmd.append("--noupx")

    # Resource dirs
    sep = os.pathsep
    for src, dst in DATA_DIRS:
        src_path = ROOT / src
        if src_path.exists():
            cmd += ["--add-data", f"{src_path}{sep}{dst}"]
        else:
            print(f"[warn] 资源目录不存在，跳过: {src_path}")

    # Hidden imports
    for mod in HIDDEN_IMPORTS:
        cmd += ["--hidden-import", mod]

    # Exclusions
    for mod in EXCLUDES:
        cmd += ["--exclude-module", mod]

    # Version info
    if version_file and not args.no_version:
        cmd += ["--version-file", str(version_file)]

    return cmd


# --------------------------------------------------------------------------- #
# Copy extra files to the dist top level
# --------------------------------------------------------------------------- #
def copy_extra_dist_files(target_dir: Path):
    """PyInstaller only packs exe/_internal, but requirements.txt, README.md and the rest
    must sit at the top level of dist/MaaAuto/ (next to the exe) so users see the same
    layout as before.
    """
    target_dir = Path(target_dir)
    copied = 0
    for name in EXTRA_DIST_FILES:
        src = ROOT / name
        if not src.exists():
            # CHANGELOG.md lives at the repo root (GitHub convention), so look one level up
            alt = ROOT.parent / name
            if alt.exists():
                src = alt
        if not src.exists():
            print(f"[warn] 附带文件不存在，跳过: {name}")
            continue
        dst = target_dir / name
        try:
            if dst.exists():
                dst.unlink()
            shutil.copy2(src, dst)
            print(f"[dist] + {name}")
            copied += 1
        except Exception as e:
            print(f"[warn] 复制 {name} 失败: {e}")
    return copied


# --------------------------------------------------------------------------- #
# Main flow
# --------------------------------------------------------------------------- #
def main():
    parser = argparse.ArgumentParser(
        description="MaaAuto 打包脚本（PyInstaller）",
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--debug", action="store_true",
                        help="保留控制台窗口")
    parser.add_argument("--onefile", action="store_true",
                        help="单文件模式（启动慢，不推荐）")
    parser.add_argument("--keep-build", action="store_true",
                        help="不自动清理 build/ 和 dist/")
    parser.add_argument("--no-clean", action="store_true",
                        help="跳过 pyinstaller --clean")
    parser.add_argument("--no-version", action="store_true",
                        help="不生成 exe 版本信息")
    args = parser.parse_args()

    print("=" * 60)
    print("MaaAuto 打包脚本")
    print("=" * 60)
    print(f"项目根目录 : {ROOT}")
    print(f"Python     : {sys.version.split()[0]} ({sys.executable})")
    print(f"模式       : {'onefile' if args.onefile else 'onedir'}"
          f" / {'console' if args.debug else 'windowed'}")
    print("=" * 60)

    if not ensure_pyinstaller():
        sys.exit(1)

    # Check that cv2 is available (vision.py multi-scale matching depends on it)
    try:
        import cv2  # noqa: F401
        print("[info] OpenCV 已安装（多尺度找图可用）")
        try:
            import numpy  # noqa: F401
        except ImportError:
            print()
            print("=" * 60)
            print("[warn] 找到 cv2 但没有 numpy —— cv2 无法工作！")
            print("       打包版的找图会直接报错。请先安装：pip install numpy")
            print("=" * 60)
            print()
    except ImportError:
        print()
        print("=" * 60)
        print("[warn] 未检测到 OpenCV，打出的包无法找图（vision.find 直接返回 None）。")
        print("       请先安装：pip install opencv-python-headless")
        print("=" * 60)
        print()

    info = read_app_info()
    print(f"[info] 应用名     : {info['APP_DISPLAY_NAME']}")
    print(f"[info] 版本号     : {info['APP_VERSION']}")
    print(f"[info] 版本元组   : {version_tuple(info['APP_VERSION'])}")

    if not args.keep_build:
        clean_artifacts()
    clean_pycache(ROOT)

    # Version file
    version_file = None
    if not args.no_version:
        version_file = write_version_file(info)
        print(f"[info] 已生成版本信息: {version_file.name}")

    # Build the command
    cmd = build_command(args, info, version_file)
    print("\n[cmd] 执行命令：")
    print("      " + " ".join(f'"{x}"' if " " in x else x for x in cmd))
    print()

    # Run it
    ret = subprocess.call(cmd, cwd=str(ROOT))
    if ret != 0:
        print("\n" + "=" * 60)
        print(f"打包失败，PyInstaller 退出码 {ret}")
        print("=" * 60)
        sys.exit(ret)

    # Copy extra files to the dist top level
    if args.onefile:
        # onefile mode has no top-level dir, so skip the extra-file copy
        print("[dist] onefile 模式跳过附带文件拷贝")
    else:
        out_dir = DIST_DIR / info["APP_NAME"]
        copy_extra_dist_files(out_dir)

    if not args.keep_build:
        clean_pycache(ROOT)

    # Wrap up
    print("\n" + "=" * 60)
    print("[OK] 打包成功")
    print("=" * 60)

    if args.onefile:
        exe = DIST_DIR / f"{info['APP_NAME']}.exe"
    else:
        exe = DIST_DIR / info["APP_NAME"] / f"{info['APP_NAME']}.exe"

    if exe.exists():
        size_mb = exe.stat().st_size / (1024 * 1024)
        print(f"产物：{exe}")
        print(f"主程序：{size_mb:.1f} MB")
        if not args.onefile:
            total = sum(f.stat().st_size for f in exe.parent.rglob("*") if f.is_file())
            print(f"整包：{total / (1024 * 1024):.1f} MB（含依赖）")
    else:
        print("[warn] 未找到预期的 exe，请检查 dist/ 目录。")


if __name__ == "__main__":
    main()